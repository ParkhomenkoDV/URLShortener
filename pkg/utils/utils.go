package utils

import (
	"crypto/rand"
	"encoding/base64"
)

// GenerateShortKey генерирует криптографически безопасный случайный короткий ключ заданной длины.
// Ключ состоит из URL-безопасных символов (A-Z, a-z, 0-9, _, -) и подходит для использования в URL.
//
// Алгоритм:
//  1. Генерируются 4 случайных байта с использованием crypto/rand (криптографически безопасный RNG)
//  2. Байты кодируются в base64 URL-encoding (убирает символы + и /, заменяя их на - и _)
//  3. Берется подстрока указанной длины из закодированной строки
//
// Параметры:
//   - length: желаемая длина ключа (рекомендуется 6-8 символов для баланса уникальности и компактности)
//
// Возвращает:
//   - string: случайный короткий ключ, состоящий только из URL-безопасных символов
//
// Паника:
//   - Если не удается сгенерировать случайные байты (крайне маловероятно в нормальных условиях)
//
// Примеры:
//   - GenerateShortKey(6) → "abc123"
//   - GenerateShortKey(8) → "aBcDeFg1"
func GenerateShortKey(length int) string {
	// Генерируем 4 случайных байта - этого достаточно для 6-символьного ключа в base64
	// 4 байта = 32 бита энтропии, что дает ~4.3 миллиарда возможных комбинаций
	b := make([]byte, 4)
	if _, err := rand.Read(b); err != nil {
		// В случае ошибки генерации случайных чисел - паника, так как это критическая ошибка системы
		panic("failed to generate random bytes: " + err.Error())
	}

	// Кодируем в base64 URL encoding и обрезаем до нужной длины
	// Base64 URL encoding использует символы: A-Z, a-z, 0-9, -, _
	// Это безопасно для использования в URL без дополнительного кодирования
	return base64.URLEncoding.EncodeToString(b)[:length]
}
